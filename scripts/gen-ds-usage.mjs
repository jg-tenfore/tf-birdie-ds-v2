#!/usr/bin/env node
/**
 * Where Birdie actually uses each MUI component — the honest "status" behind every Design System
 * page ("Used in 14 tablet files and 6 handheld files", or "Not used in Birdie yet").
 *
 *   node scripts/gen-ds-usage.mjs            # writes src/showcase/ds-docs/ds-usage-data.ts
 *   node scripts/gen-ds-usage.mjs --check    # CI: fails if the committed file is stale
 *
 * Reads every non-test .ts/.tsx under src/pos (the product — never the showcase), finds the names
 * imported from @mui/material (named imports and `@mui/material/Button`-style default imports),
 * @mui/x-date-pickers and @mui/x-data-grid, and records the files per surface:
 *   - handheld: src/pos/mobile/**
 *   - tablet:   everything else under src/pos
 * Hooks, helpers and types (useTheme, styled, alpha, SxProps…) are dropped: they aren't components.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src/pos');
const OUT = path.join(ROOT, 'src/showcase/ds-docs/ds-usage-data.ts');
const CHECK = process.argv.includes('--check');

const NOT_COMPONENTS = new Set([
  'useTheme', 'useMediaQuery', 'styled', 'alpha', 'darken', 'lighten', 'keyframes', 'createTheme',
  'ThemeProvider', 'CssBaseline', 'SxProps', 'Theme', 'SvgIconProps', 'ButtonProps', 'BoxProps',
  'TypographyProps', 'StackProps', 'PaperProps', 'ChipProps', 'TextFieldProps', 'SelectChangeEvent',
  'TooltipProps', 'IconButtonProps', 'GlobalStyles', 'Breakpoint', 'PopoverOrigin',
]);

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    if (d.isDirectory()) return walk(p);
    return /\.(ts|tsx)$/.test(d.name) && !/\.test\.tsx?$/.test(d.name) ? [p] : [];
  });

const usage = {};
const add = (name, file) => {
  if (NOT_COMPONENTS.has(name) || !/^[A-Z]/.test(name)) return;
  const rel = path.relative(ROOT, file).split(path.sep).join('/');
  const surface = rel.startsWith('src/pos/mobile/') ? 'handheld' : 'tablet';
  usage[name] ??= { tablet: [], handheld: [] };
  if (!usage[name][surface].includes(rel)) usage[name][surface].push(rel);
};

for (const file of walk(SRC)) {
  const src = fs.readFileSync(file, 'utf8');
  // import { A, B as C, type D } from '@mui/material' (and the x packages)
  for (const m of src.matchAll(/import\s+(?:type\s+)?\{([^}]+)\}\s+from\s+'@mui\/(?:material|x-date-pickers|x-data-grid)(?:\/[^']*)?'/g)) {
    if (/^import\s+type/.test(m[0])) continue;
    for (const part of m[1].split(',')) {
      const t = part.trim();
      if (!t || t.startsWith('type ')) continue;
      add(t.split(/\s+as\s+/)[0].trim(), file);
    }
  }
  // import Button from '@mui/material/Button'
  for (const m of src.matchAll(/import\s+([A-Z]\w*)\s+from\s+'@mui\/material\/(\w+)'/g)) add(m[2], file);
}

const names = Object.keys(usage).sort();
for (const n of names) {
  usage[n].tablet.sort();
  usage[n].handheld.sort();
}
const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(usage[n])},`).join('\n');
const out = `// Generated by scripts/gen-ds-usage.mjs from the imports in src/pos. Do not edit by hand.
//   node scripts/gen-ds-usage.mjs
// ${names.length} MUI components used across the product.

export interface DsUsage {
  /** Files under src/pos, outside src/pos/mobile — the counter terminal. */
  tablet: string[];
  /** Files under src/pos/mobile — the handheld. */
  handheld: string[];
}

export const MUI_USAGE: Record<string, DsUsage> = {
${body}
};
`;

if (CHECK) {
  const committed = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (committed !== out) {
    console.error(`✗ ${path.relative(ROOT, OUT)} is stale. Run node scripts/gen-ds-usage.mjs and commit it.`);
    process.exit(1);
  }
  console.log(`✓ ${path.relative(ROOT, OUT)} is up to date`);
  process.exit(0);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`✓ ${path.relative(ROOT, OUT)} — ${names.length} components`);
for (const n of names) console.log(`  ${n.padEnd(22)} tablet ${String(usage[n].tablet.length).padStart(3)}  handheld ${String(usage[n].handheld.length).padStart(3)}`);
